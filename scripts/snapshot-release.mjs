// Bakes the latest GitHub releases into src/lib/release-snapshot.ts so /download
// renders real files instantly, and still works when the GitHub API can't be
// reached (rate limit, private repo, offline). The page refreshes it live at runtime.
//
// Auth: GITHUB_TOKEN, else `gh auth token`, else anonymous. Never fails the build:
// if GitHub can't be reached the existing snapshot is kept.
import { execSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const REPO = 'UseNestBot/Nest-Bot';
const OUT = fileURLToPath(new URL('../src/lib/release-snapshot.ts', import.meta.url));

function token() {
  if (process.env.GITHUB_TOKEN) return process.env.GITHUB_TOKEN;
  try {
    return execSync('gh auth token', { stdio: ['ignore', 'pipe', 'ignore'] }).toString().trim();
  } catch {
    return '';
  }
}

try {
  const t = token();
  const res = await fetch(`https://api.github.com/repos/${REPO}/releases?per_page=10`, {
    headers: { Accept: 'application/vnd.github+json', ...(t ? { Authorization: `Bearer ${t}` } : {}) },
    signal: AbortSignal.timeout(8000),
  });
  if (!res.ok) throw new Error(`GitHub answered ${res.status}`);
  const raw = await res.json();
  const releases = raw
    .filter((r) => !r.draft)
    .map((r) => ({
      tag: r.tag_name,
      name: r.name || r.tag_name,
      publishedAt: r.published_at,
      url: r.html_url,
      prerelease: r.prerelease,
      body: r.body ?? '',
      assets: r.assets.map((a) => ({ name: a.name, size: a.size, url: a.browser_download_url, digest: a.digest ?? null })),
    }));
  if (!releases.length) throw new Error('no published releases');

  writeFileSync(
    OUT,
    `// Generated by scripts/snapshot-release.mjs. Do not edit by hand.\nimport type { Release } from './release';\n\nexport const SNAPSHOT: Release[] = ${JSON.stringify(releases, null, 2)};\n`,
  );
  console.log(`release snapshot: ${releases.map((r) => r.tag).join(', ')}`);
} catch (e) {
  console.warn(`release snapshot: kept the existing one (${e instanceof Error ? e.message : e})`);
}
